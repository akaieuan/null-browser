#[cfg(test)]
mod tests {
    use super::*;

    fn filter(rule: &Value) -> String {
        rule["trigger"]["url-filter"].as_str().unwrap().to_string()
    }

    #[test]
    fn origin_rule_anchors_and_escapes_the_host() {
        let rule = origin_rule("https://ads.example.com").expect("https origin is a rule");
        assert_eq!(
            filter(&rule),
            "^https?://([a-z0-9_-]+\\.)*ads\\.example\\.com[:/]"
        );
        assert_eq!(rule["action"]["type"], "block");
    }

    #[test]
    fn origin_rule_never_wildcards_a_single_label() {
        // Blocking "https://com" must block exactly that host —
        // wildcarding it would match every .com site's subresources.
        let rule = origin_rule("https://com").expect("single-label origin is a rule");
        assert_eq!(filter(&rule), "^https?://com[:/]");
        let ip = origin_rule("https://localhost").expect("localhost is a rule");
        assert_eq!(filter(&ip), "^https?://localhost[:/]");
    }

    #[test]
    fn origin_rule_covers_every_resource_type() {
        // No `resource-type` key at all — that is how WebKit is told
        // "all of them", `document` included.
        let rule = origin_rule("https://example.com").expect("https origin is a rule");
        assert!(rule["trigger"].get("resource-type").is_none());
    }

    #[test]
    fn origin_rule_keeps_an_explicit_port() {
        let rule = origin_rule("http://example.com:8443").expect("port origin is a rule");
        assert_eq!(
            filter(&rule),
            "^https?://([a-z0-9_-]+\\.)*example\\.com:8443/"
        );
    }

    #[test]
    fn origin_rule_drops_a_default_port() {
        let with = origin_rule("https://example.com:443").expect("origin is a rule");
        let without = origin_rule("https://example.com").expect("origin is a rule");
        assert_eq!(filter(&with), filter(&without));
    }

    #[test]
    fn origin_rule_refuses_non_web_schemes() {
        for origin in [
            "file:///etc/passwd",
            "javascript:alert(1)",
            "data:text/html,x",
            "null-event://log",
            "ftp://example.com",
        ] {
            assert!(origin_rule(origin).is_none(), "{origin} should be refused");
        }
    }

    #[test]
    fn origin_rule_refuses_garbage() {
        for origin in ["", "   ", "example.com", "https://", "not a url"] {
            assert!(
                origin_rule(origin).is_none(),
                "{origin:?} should be refused"
            );
        }
    }

    #[test]
    fn user_rules_json_is_none_without_valid_origins() {
        assert!(user_rules_json(&[]).is_none());
        assert!(user_rules_json(&["nonsense".into(), "file:///x".into()]).is_none());
    }

    #[test]
    fn user_rules_json_skips_invalid_entries() {
        let json = user_rules_json(&[
            "https://a.example".into(),
            "nonsense".into(),
            "http://b.example".into(),
        ])
        .expect("two valid origins make a list");
        let parsed: Value = serde_json::from_str(&json).expect("valid json");
        let rules = parsed.as_array().expect("an array");
        assert_eq!(rules.len(), 2);
        assert!(filter(&rules[0]).contains("a\\.example"));
        assert!(filter(&rules[1]).contains("b\\.example"));
    }

    #[test]
    fn bundled_list_is_a_usable_content_blocker() {
        let parsed: Value = serde_json::from_str(ADS_JSON).expect("ads.json is valid json");
        let rules = parsed.as_array().expect("ads.json is an array");
        assert!(!rules.is_empty(), "ads.json is empty");
        // WebKit's own cap on a compiled rule list.
        assert!(rules.len() < 150_000, "ads.json exceeds WebKit's rule cap");
        for rule in rules {
            let filter = rule["trigger"]["url-filter"]
                .as_str()
                .expect("every rule has a url-filter");
            assert!(!filter.is_empty(), "empty url-filter");
            assert!(filter.starts_with("^https?://"), "unanchored: {filter}");
            assert_eq!(rule["action"]["type"], "block");
        }
    }

    #[test]
    fn bundled_list_never_blocks_main_frame_navigations() {
        let parsed: Value = serde_json::from_str(ADS_JSON).expect("ads.json is valid json");
        for rule in parsed.as_array().expect("an array") {
            let types = rule["trigger"]["resource-type"]
                .as_array()
                .expect("the bundled rules name their resource types");
            assert!(
                !types.iter().any(|t| t == "document"),
                "the bundled list must leave navigations to on_navigation"
            );
        }
    }
}
